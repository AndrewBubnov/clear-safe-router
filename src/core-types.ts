import type { Store, useGlobalState } from './create';

export const LAZY_MARKER = Symbol('typed-router-lazy');
export type SetStateFn<T> = (action: T | ((prevState: T) => T)) => void;
export type LazyComponent = { readonly [LAZY_MARKER]: true; importFn: () => Promise<{ default: unknown }> };
export type RenderElement = unknown;
export type ScrollRestorationBehavior = 'auto' | 'smooth' | 'instant';
export type Status = 'idle' | 'pending' | 'active' | 'optimistic' | 'error';
export type Retry = number | { count: number; delay: number } | undefined;
export type Location = { pathname: string; search?: string; state?: unknown; prevLocation?: Omit<Location, 'state' | 'prevLocation'> };

type LoaderArgs = { context: Record<string, unknown>; params: Record<string, string>; setContext: SetStateFn<Record<string, unknown>>; searchParams: Record<string, string>; location: Location };
export type BeforeLoad = (args: LoaderArgs & { redirect: (target: Location | string) => Promise<void> }) => Promise<unknown> | void;
export type ClientRouteItem = {
  path: string;
  element: RenderElement | LazyComponent;
  loader?: (args: LoaderArgs & { signal: AbortSignal; attempt: number }) => Promise<unknown>;
  loaderFallback?: RenderElement;
  errorElement?: RenderElement | LazyComponent;
  fallback?: RenderElement;
  layout?: RenderElement;
  children?: ClientRouteItem[];
  staleTime?: number;
  gcTime?: number;
  optimistic?: boolean;
  pollingInterval?: number;
  retry?: Retry;
  minLoaderDuration?: number;
  scrollRestoration?: boolean | string[];
  scrollRestorationBehavior?: ScrollRestorationBehavior;
  beforeLoad?: BeforeLoad;
  afterLoad?: (args: { context: Record<string, unknown>; params: Record<string, string>; searchParams: Record<string, string> }) => Promise<void> | void;
  actions?: (args: LoaderArgs) => Record<string, (data: Record<string, unknown>) => unknown | Promise<unknown>>;
};
export type RouteItem = ClientRouteItem & { element: RenderElement; pattern: string; layouts: RenderElement[]; cacheTimestamp?: number; preloadElement?(): Promise<{ default: unknown }> };
export type BlockerState = 'blocked' | 'unblocked' | 'charged';
export type CacheReason = 'navigation' | 'prefetch' | 'invalidate' | 'polling';
export type RevalidateCacheArgs = { location: Location; routeItem?: RouteItem; signal?: AbortSignal; force?: boolean; reason?: CacheReason };
export type LoaderState<T = unknown> = { data: T; loaderError: Error | null; beforeLoadError: Error | null };
export type RouteData = { location: Location; routeItem: RouteItem | undefined; status: Status; loaderState: LoaderState };
export type RouterProps = {
  routes: RouteItem[];
  isAnimated?: boolean;
  animationDuration?: number;
  defaultRetry?: Retry;
  defaultStaleTime?: number;
  defaultLoaderFallback?: RenderElement;
  defaultErrorElement?: RenderElement;
  defaultPrefetch?: 'hover' | 'render' | 'viewport' | 'none';
  defaultHoverPrefetchDelay?: number;
  defaultMinLoaderDuration?: number;
  maxCacheSize?: number;
  errorBoundary?: unknown;
  defaultBeforeLoad?: ClientRouteItem['beforeLoad'];
  defaultAfterLoad?: ClientRouteItem['afterLoad'];
  defaultScrollRestorationBehavior?: ScrollRestorationBehavior;
  revalidateOnFocus?: boolean;
  revalidateOnReconnect?: boolean;
  context?: Record<string, unknown>;
  enableCacheSnapshot?: boolean;
};
export type LoaderStateItem = { state: LoaderState; timestamp: number; staleTime: number | undefined; reason?: CacheReason; gcTimeout?: number; gcExpiresAt?: number; gcDuration?: number };
export type CacheSnapshotEntry = { path: string; data: unknown; timestamp: number; staleTime: number | undefined; reason?: CacheReason; gcExpiresAt: number | undefined; gcDuration: number | undefined; isCached: boolean; isLoading: boolean };
export type CacheSnapshot = CacheSnapshotEntry[];
export type LoadingPromise = Promise<{ data: unknown; error: null } | { data: null; error: unknown } | undefined>;
export type ScrollMap = Record<string, [string, number][]>;
export type RouterState = {
  routeDataState: Store<RouteData>;
  scrollMapState: Store<ScrollMap>;
  contextState: Store<Record<string, unknown>>;
  blockerState: Store<BlockerState>;
  blockedTargetState: Store<Location | null>;
  cacheSnapshotState: Store<CacheSnapshot>;
  loaderMap: Map<string, LoaderStateItem>;
  loadingPromises: Map<string, LoadingPromise>;
};
export type InvalidateOptions = { withChildren?: boolean; force?: boolean; staleOnly?: boolean };
export type InvalidateResult = { path: string; data: unknown; error: Error | null };
export type RevalidateCache = (args: RevalidateCacheArgs) => LoadingPromise;
export type Options = Partial<{ onSuccess: (args: unknown) => void; onError: (args: unknown) => void }> | undefined;
export type SearchObject = Record<string, string | number | boolean | null | undefined>;
export type NavigationLocation = Omit<Location, 'search'> & { search?: string | SearchObject };
export type PathParams = Record<string, string | number>;
export type ParamsFor<TPath extends string> = TPath extends `${string}:${infer Param}/${infer Rest}` ? { [K in Param | keyof ParamsFor<Rest> as K & string]: string } : TPath extends `${string}:${infer Param}` ? { [K in Param]: string } : Record<string, never>;
export type ParamsInput<TPath extends string> = { [K in keyof ParamsFor<TPath>]: string | number };
export type HasPathSegments<TPath extends string> = TPath extends `${string}:${string}` ? true : false;
export type NavigatePathArg<TPath extends string> = string extends TPath ? { path: string; params?: PathParams; search?: string | SearchObject; state?: unknown } : TPath extends unknown ? HasPathSegments<TPath> extends true ? { path: TPath; params: ParamsInput<TPath>; pathname?: never; search?: string | SearchObject; state?: unknown } : { path: TPath; params?: never; pathname?: never; search?: string | SearchObject; state?: unknown } : never;
export type NavigatePathInput = { path: string; params?: PathParams; search?: string | SearchObject; state?: unknown };
export type Synchronizer = <T>(subscribe: (updater: () => void) => () => void, getSnapshot: () => T, getServerSnapshot?: () => T) => T;
export type RouterType = {
  runtime: { navigate(arg: Location): Promise<void>; invalidate(pathList?: string | string[], options?: InvalidateOptions): Promise<InvalidateResult[]>; prefetch(location: Location, signal?: AbortSignal): Promise<void>; syncCacheSnapshot(): void };
  hooks: {
    useBlockerState(): ReturnType<typeof useGlobalState<BlockerState>>;
    useScrollMap(): ReturnType<typeof useGlobalState<ScrollMap>>;
    useContextState(): ReturnType<typeof useGlobalState<Record<string, unknown>>>;
    useBlockedTargetState(): ReturnType<typeof useGlobalState<Location | null>>;
    useParams<T>(): T;
    useNavigate(): { (arg: NavigationLocation | string | -1): Promise<void>; <const TPath extends string>(arg: NavigatePathArg<TPath>): Promise<void> };
    useAction(action: string, options?: Options): (arg: Record<string, unknown>) => Promise<{ data: unknown; error: Error | null }>;
    useScrollRestoration(restorationBehavior: ScrollRestorationBehavior): () => void;
    useRouteDataSelector<T>(callback: (arg: RouteData) => T): T;
    useCacheSnapshot(): CacheSnapshot;
    useSetLocation(): (location: Location) => void;
  };
};
